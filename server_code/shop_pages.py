def _cat_label(p):
  key = p["category"] or ""
  if catalog is not None:
    label = catalog.cat_label(key)
    if label:
      return label
  return key.replace("_", " ").capitalize() or ("Food & drink" if p["kind"] == "restaurant" else "Shop")


def _schema_type(p):
  t = SCHEMA_TYPES.get(p["category"] or "")
  return t or ("Restaurant" if p["kind"] == "restaurant" else "Store")


def _money(price, cur, unit):
  if price is None:
    return ""
  amount = str(int(round(price))) if abs(price - round(price)) < 0.005 else "%.2f" % price
  cur = cur or "€"
  s = ("%s %s" % (amount, cur)) if cur in ("kr", "zł", "CHF") else cur + amount
  if unit == "from":
    return "from " + s
  return s + ((unit if unit.startswith("/") else " " + unit) if unit else "")


def _count(p, src):
  ua = str((anvil.server.request.headers or {}).get("user-agent") or "")
  if not ua or BOTS.search(ua):
    return
  try:
    day = now().date().isoformat()
    row = app_tables.page_hits.get(place=p, day=day, src=src)
    if row is None:
      app_tables.page_hits.add_row(place=p, day=day, src=src, n=1)
    else:
      row["n"] = (row["n"] or 0) + 1
  except Exception as ex:  # page_hits waits for the Schema Mismatch accept: the page still shows
    print("page_hits:", ex)


def _resp(status, body, ctype="text/html; charset=utf-8", cache="public, max-age=300", extra=None):
  h = {"Cache-Control": cache}
  h.update(extra or {})
  return anvil.server.HttpResponse(status, anvil.BlobMedia(ctype, body.encode("utf-8") if isinstance(body, str) else body),
                                   headers=h)


