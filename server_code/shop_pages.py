def _page(title, body, desc="", canonical="", image="", noindex=False, ld=None, status=200):
  o = origin()
  head = ['<!doctype html><html lang="en"><head><meta charset="utf-8">',
          '<meta name="viewport" content="width=device-width, initial-scale=1">',
          "<title>%s</title>" % e(title), '<meta name="description" content="%s">' % e(desc)]
  if canonical:
    head.append('<link rel="canonical" href="%s">' % e(canonical))
  head.append('<meta name="robots" content="%s">' % ("noindex, follow" if noindex else
                                                     "index, follow, max-image-preview:large, max-snippet:-1"))
  head += ['<meta property="og:type" content="website"><meta property="og:site_name" content="MonShop">',
           '<meta property="og:title" content="%s">' % e(title), '<meta property="og:description" content="%s">' % e(desc)]
  if canonical:
    head.append('<meta property="og:url" content="%s">' % e(canonical))
  img = image or o + "/_/theme/og-image.png"
  head += ['<meta property="og:image" content="%s">' % e(img), '<meta name="twitter:card" content="summary_large_image">',
           '<meta name="theme-color" content="#FFF8EF">',
           '<link rel="icon" type="image/svg+xml" href="%s/_/theme/logo.svg">' % e(o),
           '<link rel="preconnect" href="https://fonts.googleapis.com">'
           '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
           '<link href="https://fonts.googleapis.com/css2?family=Figtree:wght@400;600;700;800;900&display=swap" rel="stylesheet">']
  if ld:
    head.append('<script type="application/ld+json">%s</script>'
                % json.dumps(ld, ensure_ascii=False).replace("</", "<\\/"))
  head.append("<style>%s</style></head><body>" % CSS)
  top = ('<div class="wrap"><header class="top"><a class="brand" href="%s/"><img src="%s/_/theme/logo.svg" alt="" '
         'width="34" height="34">MonShop</a><a class="btn ghost sm" href="%s/#map">Explore the map</a></header>' % (o, o, o))
  foot = ('<footer>MonShop: the independent shops on your street. <a href="%s/shops">All shops</a> · '
          '<a href="%s/about">About</a> · <a href="%s/#legal/privacy">Privacy &amp; Terms</a> · '
          'Made by <a href="https://arkvital.com">Arkvital</a>, Montreal.</footer></div></body></html>' % (o, o, o))
  return _resp(status, "".join(head) + top + body + foot)


def _not_found():
  o = origin()
  body = ('<div class="card" style="margin:40px 0;text-align:center"><div style="font-size:60px" aria-hidden="true">🚪</div>'
          '<h1 style="font-size:32px">This door is closed</h1><p class="muted">We couldn\'t find that shop. It may not be '
          'on MonShop yet, or it has left.</p><p><a class="btn" href="%s/#map">See the shops near you</a></p></div>' % o)
  return _page("Shop not found · MonShop", body, noindex=True, status=404)


def _place(place_id):
  p = by_id(app_tables.places, place_id)
  if p is None or p["status"] != "approved":
    return None
  return p


def _first_photo(p):
  if p["cover"] is not None:
    return p["cover"]
  for it in active_items(p):
    if it["photo"] is not None:
      return it["photo"]
  return None


def shop_html(p, src="web"):
  """The page for an approved place (the route counts the hit, then calls this)."""
  o = origin()
  pid = rid(p)
  url = "%s/s/%s" % (o, pid)
  items = active_items(p)[:12]
  week = hours_mod.week_of(p)
  st = hours_mod.open_state(p, None, week=week) if week else None
  sp = special_of(p)
  cat = _cat_label(p)
  name = p["name"] or "A MonShop place"
  demo = bool(p["is_demo"])
  desc = (p["tagline"] or "") or ("%s on MonShop" % cat)
  desc = "%s · %s. %s" % (name, cat, desc) if p["tagline"] else "%s: %s in %s. See what's on the shelf today." % (
    name, cat.lower(), (p["address"] or "your neighbourhood"))
  has_photo = _first_photo(p) is not None
  img = "%s/cover.jpg" % url if has_photo else ""
  # schema.org
  ld = {"@context": "https://schema.org", "@type": _schema_type(p), "@id": url + "#place", "name": name, "url": url,
        "description": (p["about"] or p["tagline"] or desc)[:500], "image": img or o + "/_/theme/og-image.png"}
  if p["address"]:
    ld["address"] = {"@type": "PostalAddress", "streetAddress": p["address"]}
  if p["lat"] is not None:
    ld["geo"] = {"@type": "GeoCoordinates", "latitude": p["lat"], "longitude": p["lng"]}
  if p["phone"]:
    ld["telephone"] = p["phone"]
  if p["website"]:
    ld["sameAs"] = [p["website"]]
  if week:
    ld["openingHoursSpecification"] = hours_mod.schema_specs(week)
  # hero
  color = GRADS.get(p["color"] or "g1", GRADS["g1"])
  if has_photo:
    hero = ('<div class="hero"><div class="bg" style="background-image:url(\'%s/cover.jpg\')"></div><div class="shade"></div>'
            % url)
  else:
    hero = ('<div class="hero light" style="background:linear-gradient(135deg,%s)"><span class="emo" aria-hidden="true">%s</span>'
            '<div class="shade"></div>' % (color, e(p["emoji"] or "🛍️")))
  pill = ""
  if st:
    pill = '<span class="pill %s"><span class="dot" aria-hidden="true"></span>%s</span>' % (e(st["tone"]), e(st["label"]))
  hero += ('<div class="in">%s<h1>%s</h1><div class="tag">%s%s</div></div></div>'
           % (pill, e(name), e(cat), (" · " + e(p["tagline"])) if p["tagline"] else ""))
  parts = [hero]
  if demo:
    parts.append('<p class="demo">🧪 This is a demo shop: a made-up name at a real address in Riga, to show how MonShop '
                 'works. Real shops near you are on the map.</p>')
  main = []
  if sp:
    main.append('<div class="special"><span aria-hidden="true">✨</span><span>%s</span></div>' % e(sp["text"]))
  main.append("<h2>On the shelf today</h2>")
  if items:
    tiles = []
    for it in items:
      price = _money(it["price"], p["currency"], it["unit"] or "")
      if it["thumb"] is not None or it["photo"] is not None:
        ph = '<div class="ph" style="background-image:url(\'%s/i/%s.jpg\')"></div>' % (url, rid(it))
      else:
        ph = ('<div class="ph" style="background:linear-gradient(135deg,%s)" aria-hidden="true">%s</div>'
              % (GRADS.get(it["color"] or "g3", GRADS["g3"]), e(it["emoji"] or "🛍️")))
      tiles.append('<div class="it">%s<b>%s</b>%s</div>' % (ph, e(it["title"] or ""),
                                                             ("<span>%s</span>" % e(price)) if price else ""))
    main.append('<div class="shelf">%s</div>' % "".join(tiles))
  else:
    main.append('<p class="muted">Nothing posted yet. Pop in and see for yourself!</p>')
  if p["about"]:
    main.append('<h2 style="margin-top:26px">About %s</h2><p>%s</p>' % (e(name), e(p["about"])))
  side = ['<div class="card"><div class="five"><div class="b" aria-hidden="true">5%%</div><div><b>Bookmark for 5%% off</b>'
          '<div class="muted" style="font-size:14px">Members get 5%% off every visit. Free.</div></div></div>'
          '<div class="cta"><a class="btn" href="%s/#shop/%s">🔖 Open in MonShop &amp; bookmark</a></div></div>' % (o, pid)]
  info = ['<div class="card">']
  directions = "https://www.google.com/maps/dir/?api=1&destination=%s,%s" % (p["lat"], p["lng"])
  info.append('<div class="r"><span class="i" aria-hidden="true">📍</span><span>%s<br><a href="%s" target="_blank" '
              'rel="noopener">Get directions →</a></span></div>' % (e(p["address"] or "Address coming soon"), e(directions)))
  if week:
    today = st["today"] if st else ""
    rows = "".join('<tr class="%s"><td>%s</td><td>%s</td></tr>' % ("today" if d == today else "", hours_mod.DAY_FULL[i],
                                                                     e(hours_mod.day_text(week.get(d) or [])))
                   for i, d in enumerate(hours_mod.DAYS))
    info.append('<div class="r"><span class="i" aria-hidden="true">🕐</span><table class="wk" aria-label="Opening hours">'
                '%s</table></div>' % rows)
  elif p["hours"]:
    info.append('<div class="r"><span class="i" aria-hidden="true">🕐</span><span>%s</span></div>' % e(p["hours"]))
  if p["phone"]:
    info.append('<div class="r"><span class="i" aria-hidden="true">📞</span><a href="tel:%s">%s</a></div>'
                % (e(re.sub(r"[^\d+]", "", p["phone"])), e(p["phone"])))
  if p["website"]:
    info.append('<div class="r"><span class="i" aria-hidden="true">🌐</span><a href="%s" target="_blank" rel="noopener">%s</a></div>'
                % (e(p["website"]), e(re.sub(r"^https?://", "", p["website"]).rstrip("/"))))
  info.append("</div>")
  parts.append('<div class="grid"><div>%s</div><div class="side">%s%s</div></div>' % ("".join(main), "".join(side),
                                                                                     "".join(info)))
  return _page("%s · %s · MonShop" % (name, cat), "".join(parts), desc=desc, canonical=url, image=img,
               noindex=demo, ld=ld if not demo else None)


