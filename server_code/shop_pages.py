def cover_media(p):
  return _first_photo(p)


ROUTE = getattr(anvil.server, "route", None)
if ROUTE:
  @ROUTE("/s/:place_id")
  def shop_page(place_id, **params):
    p = _place(place_id)
    if p is None:
      return _not_found()
    q = getattr(anvil.server.request, "query_params", None) or {}
    src = "qr" if str(q.get("src") or "") == "qr" else "web"
    _count(p, src)
    return shop_html(p, src)

  @ROUTE("/s/:place_id/cover.jpg")
  def shop_cover(place_id, **params):
    p = _place(place_id)
    m = cover_media(p) if p is not None else None
    if m is None:
      return anvil.server.HttpResponse(302, "", headers={"Location": origin() + "/_/theme/og-image.png"})
    return anvil.server.HttpResponse(200, m, headers={"Cache-Control": "public, max-age=3600"})

  @ROUTE("/s/:place_id/i/:item")
  def shop_item_photo(place_id, item, **params):
    p = _place(place_id)
    it = by_id(app_tables.items, str(item or "").replace(".jpg", "")) if p is not None else None
    if it is None or it["place"] != p or not it["active"] or (it["thumb"] is None and it["photo"] is None):
      return anvil.server.HttpResponse(404, "Not found")
    return anvil.server.HttpResponse(200, it["thumb"] or it["photo"], headers={"Cache-Control": "public, max-age=86400"})

  @ROUTE("/shops")
  def shop_list(**params):
    return shops_html()
